interface LanguageContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (text: string) => string;
  formatDate: (date: Date | number, pattern: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);
const STORAGE_KEY = "vms_language";

function getInitialLanguage(): AppLanguage {
  if (typeof window === "undefined") return "en";
  const savedLanguage = window.localStorage.getItem(STORAGE_KEY);
  if (savedLanguage === "en" || savedLanguage === "ta") return savedLanguage;
  return navigator.language.toLowerCase().startsWith("ta") ? "ta" : "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(getInitialLanguage);

  const setLanguage = useCallback((nextLanguage: AppLanguage) => {
    setLanguageState(nextLanguage);
    window.localStorage.setItem(STORAGE_KEY, nextLanguage);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "ta" ? "ta" : "en";
  }, [language]);

  const t = useCallback((text: string) => translations[language][text] ?? text, [language]);
  const formatDate = useCallback((date: Date | number, pattern: string) =>
    formatDateFns(date, pattern, { locale: language === "ta" ? ta : enUS }), [language]);
  const value = useMemo(() => ({
    language,
    setLanguage,
    t,
    formatDate,
  }), [language, setLanguage, t, formatDate]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}
